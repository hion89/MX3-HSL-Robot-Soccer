#  D405 카메라(YOLO 3D 검출) 기반으로 경기장 안에서 로봇의 절대 위치를
#  추정하는 "비전 로컬라이제이션" 코드만 모은다.
#
#  [설계 원칙 — 왜 이렇게 단순화했는가]
#  --------------------------------------------------------------------------
#   - 과거 2번의 포팅 실패는 pose_filter / L0~L3 다층 구조의 복잡도에
#     측정 버그가 숨었던 것이 원인이었다.
#   - 이번 구조에서는 "필터링/융합"은 배포 패키지 robot_localization(EKF)에
#     전부 위임하고, 이 서브패키지는 오직 "지도 위 절대 위치 측정값"만
#     계산한다. 즉 책임을 한 줄로 좁힌다.
#
#  [모듈 구성]
#   - field_geometry      : 경기장 치수(연습장/대회 규격 프로파일) 정의
#   - landmark_pose_solver: (거리, 방위) 관측 → 로봇 pose Gauss-Newton 추정 코어
#                           (ROS 무관 순수 연산. grid disambiguation 제거)
#   - field_landmarks     : 경기장 치수로부터 점 랜드마크(GP/X/T/L) 자동 생성
#
#  [중요]
#   - 이 서브패키지의 3개 모듈은 ROS 의존성이 전혀 없다(numpy/yaml/math 만 사용).
#     → 실로봇/ROS 없이 standalone pytest 로 단위 검증 가능하다.
#     실제 ROS 노드(field_landmark_localizer_node)는 Phase 2 에서 별도로 추가하며,
#     이 코어들을 import 해서 사용한다.
